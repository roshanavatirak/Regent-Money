/**
 * Returns a deterministic, non-repeating humorous message based on day of month.
 * Day 1 to 30 each have their own distinct message.
 */
export function getDailyHumorMessage(slot: 'morning' | 'evening'): HumorousMessage {
  const now = new Date();
  // Using day of month (1 - 31), normalized to 0 - 29
  const dayIndex = (now.getDate() - 1) % 30;

  if (slot === 'morning') {
    return MORNING_HUMOR_MESSAGES[dayIndex];
  } else {
    return EVENING_HUMOR_MESSAGES[dayIndex];
  }
}
