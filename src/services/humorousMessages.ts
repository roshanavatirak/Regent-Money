export function getDailyHumorMessage(slot: 'morning' | 'evening'): HumorousMessage {
  const now = new Date();
  const dayIndex = (now.getDate() - 1) % 30;

  if (slot === 'morning') {
    return MORNING_HUMOR_MESSAGES[dayIndex];
  } else {
    return EVENING_HUMOR_MESSAGES[dayIndex];
  }
}
